-- 공연이 열리는 도시 — 보딩패스의 도착지
--
-- 보딩패스는 "출발 = 자택(HOME), 도착 = 관람 도시"인 가상의 비행기 티켓이다. 그런데 도착지가
-- 'SEOUL'로 고정돼 있었다. 시드 50건의 공연장 33곳이 전부 서울이라 지금까지는 맞는 값이었지만,
-- 관리자가 대전이나 부산 공연을 등록하면 티켓에 엉뚱한 도시가 찍힌다.
--
-- **왜 venue_name에서 뽑아내지 않는가**: 자유 텍스트라 도시를 알아낼 방법이 없다.
-- '대전예술의전당'은 이름에 도시가 들어 있지만 '블루스퀘어'·'샤롯데씨어터'·'KSPO돔'은 없다.
-- 이름에서 추측하는 규칙을 만들면 대부분의 공연장에서 틀리고, 틀렸다는 걸 알아채기도 어렵다.
-- 그래서 관리자가 고르는 칸으로 둔다.
--
-- **왜 한글로 저장하는가**: 관리 화면에서 고르는 값 그대로라 DB를 열어봐도 읽힌다.
-- 보딩패스에 찍을 영문(SEOUL/DAEJEON)은 앱이 constants/cities.ts에서 옮긴다.
-- 반대로 영문을 저장하면 DB는 짧아지지만 관리 화면과 저장값이 달라져 대조하기 번거롭다.
--
-- **왜 check 제약을 두는가**: 영문으로 옮길 표에 없는 값이 들어오면 보딩패스에 찍을 게 없어진다.
-- 17개 시·도는 대한민국 전체를 덮으므로 "목록에 없는 도시"가 생기지 않는다.
-- 제약이 있으면 SQL로 직접 넣을 때도 오타가 막힌다.

alter table events add column if not exists city text not null default '서울';

-- add constraint에는 if not exists가 없어서, 다시 만들 수 있도록 먼저 지운다
alter table events drop constraint if exists events_city_valid;
alter table events add constraint events_city_valid check (
  city in (
    '서울', '부산', '대구', '인천', '광주', '대전', '울산', '세종',
    '경기', '강원', '충북', '충남', '전북', '전남', '경북', '경남', '제주'
  )
);

-- 시드 50건은 공연장이 전부 서울이라 기본값이 그대로 맞다.
